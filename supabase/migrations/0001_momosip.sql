-- MomoSip ordering platform schema. Run this in Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  role text not null default 'staff' check (role in ('super_admin','staff')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  name text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  is_vegetarian boolean not null default true,
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.banners (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  subtitle text,
  image_url text,
  is_active boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text,
  order_type text not null default 'takeaway' check (order_type in ('takeaway','dine_in')),
  notes text,
  status text not null default 'pending' check (status in ('pending','preparing','ready','completed','cancelled')),
  subtotal numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(10,2) not null,
  quantity int not null check (quantity > 0),
  line_total numeric(10,2) not null
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists products_category_idx on public.products(category_id);

create or replace function public.current_user_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=auth.uid() and is_active=true $$;

create or replace function public.is_active_staff()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and is_active=true and role in ('staff','super_admin')) $$;

create or replace function public.is_super_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and is_active=true and role='super_admin') $$;

-- Profile row is created on first auth user creation. Promote the first admin manually below.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.profiles(id,email,full_name,role)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name',''), 'staff')
  on conflict(id) do update set email=excluded.email;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.banners enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Public menu data
create policy "Public can view categories" on public.categories for select using (true);
create policy "Public can view available products" on public.products for select using (is_available=true or public.is_active_staff());
create policy "Public can view active banners" on public.banners for select using (is_active=true or public.is_active_staff());

-- Admin-only catalogue and banner management
create policy "Admins manage categories" on public.categories for all using (public.is_super_admin()) with check (public.is_super_admin());
create policy "Admins manage products" on public.products for all using (public.is_super_admin()) with check (public.is_super_admin());
create policy "Admins manage banners" on public.banners for all using (public.is_super_admin()) with check (public.is_super_admin());

-- Staff and admins can see orders and order lines; only admins can delete.
create policy "Staff view orders" on public.orders for select using (public.is_active_staff());
create policy "Staff update orders" on public.orders for update using (public.is_active_staff()) with check (public.is_active_staff());
create policy "Admins delete orders" on public.orders for delete using (public.is_super_admin());
create policy "Staff view order items" on public.order_items for select using (public.is_active_staff());
-- Order items are created only inside the trusted place_order() function; staff do not edit line items directly.

create policy "Users view own profile and admins view all" on public.profiles
for select using (id=auth.uid() or public.is_super_admin());
create policy "Admins update profiles" on public.profiles
for update using (public.is_super_admin()) with check (public.is_super_admin());

-- Place an order securely: price is always read from the database, never trusted from the browser.
create or replace function public.place_order(order_data jsonb)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare
  v_order_id uuid;
  v_order_number bigint;
  v_subtotal numeric(10,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty int;
  v_name text;
  v_phone text;
  v_type text;
  v_notes text;
begin
  if auth.uid() is not null and not public.is_active_staff() then
    raise exception 'This account is not active.';
  end if;
  v_name := nullif(trim(order_data->>'customer_name'),'');
  if v_name is null then raise exception 'Customer name is required.'; end if;
  v_phone := nullif(trim(order_data->>'customer_phone'),'');
  v_type := coalesce(order_data->>'order_type','takeaway');
  if v_type not in ('takeaway','dine_in') then raise exception 'Invalid order type.'; end if;
  v_notes := left(coalesce(order_data->>'notes',''),500);
  if jsonb_typeof(order_data->'items') <> 'array' or jsonb_array_length(order_data->'items')=0 then
    raise exception 'Add at least one item.';
  end if;

  insert into public.orders(customer_name,customer_phone,order_type,notes,created_by)
  values(v_name,v_phone,v_type,v_notes,auth.uid())
  returning id,order_number into v_order_id,v_order_number;

  for v_item in select * from jsonb_array_elements(order_data->'items') loop
    select * into v_product from public.products
    where id=(v_item->>'product_id')::uuid and is_available=true;
    if not found then raise exception 'One of the selected products is unavailable.'; end if;
    v_qty := greatest(1,least(99,(v_item->>'quantity')::int));
    insert into public.order_items(order_id,product_id,product_name,unit_price,quantity,line_total)
    values(v_order_id,v_product.id,v_product.name,v_product.price,v_qty,v_product.price*v_qty);
    v_subtotal := v_subtotal + v_product.price*v_qty;
  end loop;

  update public.orders set subtotal=v_subtotal,total=v_subtotal where id=v_order_id;
  return jsonb_build_object('id',v_order_id,'order_number',v_order_number,'total',v_subtotal);
end;
$$;
grant execute on function public.place_order(jsonb) to anon, authenticated;

